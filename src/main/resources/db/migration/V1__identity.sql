CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(120) NOT NULL,
    email           VARCHAR(160) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    phone           VARCHAR(30),
    account_status  VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_status CHECK (account_status IN ('PENDING','ACTIVE','SUSPENDED'))
);

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   VARCHAR(40)  NOT NULL,
    description VARCHAR(200),
    CONSTRAINT uq_roles_name UNIQUE (role_name)
);

CREATE TABLE user_roles (
    user_id     BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id     BIGINT      NOT NULL REFERENCES roles(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    assigned_by BIGINT      REFERENCES users(id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash  VARCHAR(100) NOT NULL,
    expires_at  TIMESTAMPTZ  NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_reset_token_hash UNIQUE (token_hash)
);

CREATE TABLE organizations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_name          VARCHAR(200) NOT NULL,
    display_name        VARCHAR(120) NOT NULL,
    organization_type   VARCHAR(20)  NOT NULL,
    registration_number VARCHAR(60),
    tax_id              VARCHAR(30),
    email               VARCHAR(160),
    phone               VARCHAR(30),
    address_line1       VARCHAR(200),
    address_line2       VARCHAR(200),
    city                VARCHAR(80),
    state               VARCHAR(80),
    postal_code         VARCHAR(20),
    country             VARCHAR(60)  NOT NULL DEFAULT 'India',
    verification_status VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_org_type CHECK (organization_type IN ('BUYER','MANUFACTURER','PLATFORM')),
    CONSTRAINT ck_org_verification CHECK (verification_status IN ('PENDING','VERIFIED','REJECTED'))
);

CREATE TABLE organization_members (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT      NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    user_id         BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    membership_role VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    active          BOOLEAN     NOT NULL DEFAULT TRUE,
    joined_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_org_member UNIQUE (organization_id, user_id),
    CONSTRAINT ck_member_role CHECK (membership_role IN ('OWNER','ADMIN','MEMBER'))
);

CREATE TABLE manufacturer_profiles (
    organization_id    BIGINT PRIMARY KEY REFERENCES organizations(id) ON DELETE CASCADE,
    description        TEXT,
    years_in_operation INTEGER,
    website_url        VARCHAR(255),
    verification_notes TEXT,
    approved_at        TIMESTAMPTZ,
    approved_by        BIGINT REFERENCES users(id),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_years_positive CHECK (years_in_operation IS NULL OR years_in_operation >= 0)
);

CREATE INDEX idx_org_members_user ON organization_members(user_id);
CREATE INDEX idx_org_type_status  ON organizations(organization_type, verification_status);