CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title      VARCHAR(160) NOT NULL,
    message    TEXT         NOT NULL,
    link_url   VARCHAR(255),
    read_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Audit rows are never deleted
CREATE TABLE audit_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT       REFERENCES users(id),
    action        VARCHAR(60)  NOT NULL,
    entity_type   VARCHAR(60)  NOT NULL,
    entity_id     BIGINT,
    details       TEXT,
    ip_address    VARCHAR(45),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE contact_requests (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    email      VARCHAR(160) NOT NULL,
    subject    VARCHAR(160) NOT NULL,
    message    TEXT         NOT NULL,
    status     VARCHAR(20)  NOT NULL DEFAULT 'NEW',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_contact_status CHECK (status IN ('NEW','IN_PROGRESS','RESOLVED'))
);

-- Only a buyer with a real order can review (prevents fake reviews)
CREATE TABLE reviews (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                     BIGINT      NOT NULL REFERENCES production_orders(id),
    buyer_organization_id        BIGINT      NOT NULL REFERENCES organizations(id),
    manufacturer_organization_id BIGINT      NOT NULL REFERENCES organizations(id),
    reviewer_user_id             BIGINT      NOT NULL REFERENCES users(id),
    rating                       INTEGER     NOT NULL,
    comment                      TEXT,
    verified_purchase            BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_review_per_order UNIQUE (order_id, buyer_organization_id),
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE disputes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT       NOT NULL REFERENCES production_orders(id),
    opened_by   BIGINT       NOT NULL REFERENCES users(id),
    reason      VARCHAR(160) NOT NULL,
    description TEXT,
    status      VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    resolution  TEXT,
    resolved_by BIGINT       REFERENCES users(id),
    resolved_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_dispute_status CHECK (status IN ('OPEN','UNDER_REVIEW','RESOLVED','REJECTED'))
);

CREATE TABLE recalls (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id     BIGINT      NOT NULL REFERENCES batches(id),
    initiated_by BIGINT      NOT NULL REFERENCES users(id),
    reason       TEXT        NOT NULL,
    severity     VARCHAR(20) NOT NULL,
    status       VARCHAR(20) NOT NULL DEFAULT 'INITIATED',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_recall_severity CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    CONSTRAINT ck_recall_status CHECK (status IN ('INITIATED','NOTIFIED','CLOSED'))
);

CREATE TABLE recall_recipients (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recall_id              BIGINT      NOT NULL REFERENCES recalls(id) ON DELETE CASCADE,
    organization_id        BIGINT      NOT NULL REFERENCES organizations(id),
    notified_at            TIMESTAMPTZ,
    acknowledgement_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    acknowledged_at        TIMESTAMPTZ,
    CONSTRAINT uq_recall_recipient UNIQUE (recall_id, organization_id),
    CONSTRAINT ck_recall_ack CHECK (acknowledgement_status IN ('PENDING','ACKNOWLEDGED'))
);

CREATE INDEX idx_notifications_user ON notifications(user_id, read_at);
CREATE INDEX idx_audit_entity       ON audit_logs(entity_type, entity_id);
CREATE INDEX idx_audit_created      ON audit_logs(created_at);
CREATE INDEX idx_reviews_mfr        ON reviews(manufacturer_organization_id);
CREATE INDEX idx_disputes_order     ON disputes(order_id);
CREATE INDEX idx_recalls_batch      ON recalls(batch_id);