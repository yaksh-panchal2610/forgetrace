CREATE TABLE payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_order_id BIGINT        NOT NULL REFERENCES production_orders(id),
    payment_reference   VARCHAR(40)   NOT NULL,
    provider            VARCHAR(30)   NOT NULL DEFAULT 'SANDBOX',
    provider_reference  VARCHAR(100),
    idempotency_key     VARCHAR(80)   NOT NULL,
    amount              NUMERIC(14,2) NOT NULL,
    currency            VARCHAR(3)    NOT NULL DEFAULT 'INR',
    payment_method      VARCHAR(20)   NOT NULL,
    status              VARCHAR(20)   NOT NULL DEFAULT 'CREATED',
    failure_reason      VARCHAR(255),
    paid_at             TIMESTAMPTZ,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_payment_reference UNIQUE (payment_reference),
    CONSTRAINT uq_payment_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_method CHECK (payment_method IN ('CARD','UPI','NET_BANKING','WALLET','SANDBOX')),
    CONSTRAINT ck_payment_status CHECK (status IN ('CREATED','PENDING','SUCCEEDED','FAILED','REFUNDED'))
);

CREATE TABLE shipments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_order_id BIGINT       NOT NULL REFERENCES production_orders(id),
    carrier_name        VARCHAR(100) NOT NULL,
    tracking_number     VARCHAR(100),
    dispatch_date       DATE,
    expected_delivery   DATE,
    delivered_at        TIMESTAMPTZ,
    status              VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_shipment_status CHECK (status IN ('PENDING','DISPATCHED','IN_TRANSIT','DELIVERED','RETURNED','CANCELLED')),
    CONSTRAINT ck_shipment_dates CHECK (expected_delivery IS NULL OR dispatch_date IS NULL OR expected_delivery >= dispatch_date)
);

CREATE TABLE shipment_batches (
    shipment_id BIGINT        NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
    batch_id    BIGINT        NOT NULL REFERENCES batches(id),
    quantity    NUMERIC(14,3) NOT NULL,
    PRIMARY KEY (shipment_id, batch_id),
    CONSTRAINT ck_shipment_batch_qty CHECK (quantity > 0)
);

CREATE TABLE shipment_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id  BIGINT       NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
    event_status VARCHAR(20)  NOT NULL,
    event_time   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    location     VARCHAR(160),
    remarks      VARCHAR(255),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_payments_order       ON payments(production_order_id);
CREATE INDEX idx_shipments_order      ON shipments(production_order_id);
CREATE INDEX idx_shipment_events_ship ON shipment_events(shipment_id, event_time);