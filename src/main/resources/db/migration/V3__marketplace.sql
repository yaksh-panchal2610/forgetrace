CREATE TABLE file_objects (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket            VARCHAR(100) NOT NULL,
    object_key        VARCHAR(500) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type      VARCHAR(100) NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    uploaded_by       BIGINT       NOT NULL REFERENCES users(id),
    organization_id   BIGINT       REFERENCES organizations(id),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_file_object_key UNIQUE (object_key),
    CONSTRAINT ck_file_size CHECK (size_bytes > 0)
);

CREATE TABLE rfqs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_number            VARCHAR(30)   NOT NULL,
    buyer_organization_id BIGINT        NOT NULL REFERENCES organizations(id),
    created_by            BIGINT        NOT NULL REFERENCES users(id),
    title                 VARCHAR(160)  NOT NULL,
    description           TEXT,
    process_id            BIGINT        NOT NULL REFERENCES manufacturing_processes(id),
    material_id           BIGINT        NOT NULL REFERENCES materials(id),
    quantity              NUMERIC(14,3) NOT NULL,
    quantity_unit         VARCHAR(20)   NOT NULL DEFAULT 'pcs',
    specifications        JSONB,
    tolerance_notes       TEXT,
    delivery_date         DATE          NOT NULL,
    delivery_address      TEXT          NOT NULL,
    quote_deadline        TIMESTAMPTZ   NOT NULL,
    status                VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_rfq_number UNIQUE (rfq_number),
    CONSTRAINT ck_rfq_quantity CHECK (quantity > 0),
    CONSTRAINT ck_rfq_status CHECK (status IN ('DRAFT','OPEN','CLOSED','AWARDED','CANCELLED','EXPIRED'))
);

CREATE TABLE rfq_attachments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_id      BIGINT      NOT NULL REFERENCES rfqs(id) ON DELETE CASCADE,
    file_id     BIGINT      NOT NULL REFERENCES file_objects(id),
    uploaded_by BIGINT      NOT NULL REFERENCES users(id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE quotations (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_number             VARCHAR(30)   NOT NULL,
    rfq_id                       BIGINT        NOT NULL REFERENCES rfqs(id),
    manufacturer_organization_id BIGINT        NOT NULL REFERENCES organizations(id),
    submitted_by                 BIGINT        NOT NULL REFERENCES users(id),
    version_number               INTEGER       NOT NULL DEFAULT 1,
    unit_price                   NUMERIC(14,2) NOT NULL,
    setup_fee                    NUMERIC(14,2) NOT NULL DEFAULT 0,
    tax_amount                   NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_amount                 NUMERIC(14,2) NOT NULL,
    currency                     VARCHAR(3)    NOT NULL DEFAULT 'INR',
    lead_time_days               INTEGER       NOT NULL,
    valid_until                  TIMESTAMPTZ   NOT NULL,
    terms                        TEXT,
    status                       VARCHAR(20)   NOT NULL DEFAULT 'SUBMITTED',
    created_at                   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_quotation_number UNIQUE (quotation_number),
    CONSTRAINT uq_quotation_version UNIQUE (rfq_id, manufacturer_organization_id, version_number),
    CONSTRAINT ck_quote_version CHECK (version_number >= 1),
    CONSTRAINT ck_quote_money CHECK (unit_price >= 0 AND setup_fee >= 0 AND tax_amount >= 0 AND total_amount >= 0),
    CONSTRAINT ck_quote_lead CHECK (lead_time_days > 0),
    CONSTRAINT ck_quote_status CHECK (status IN ('SUBMITTED','SUPERSEDED','ACCEPTED','REJECTED','EXPIRED','WITHDRAWN'))
);

-- UNIQUE accepted_quotation_id + UNIQUE rfq_id => a quote can never create two orders
CREATE TABLE production_orders (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number                 VARCHAR(30)   NOT NULL,
    accepted_quotation_id        BIGINT        NOT NULL REFERENCES quotations(id),
    rfq_id                       BIGINT        NOT NULL REFERENCES rfqs(id),
    buyer_organization_id        BIGINT        NOT NULL REFERENCES organizations(id),
    manufacturer_organization_id BIGINT        NOT NULL REFERENCES organizations(id),
    quantity                     NUMERIC(14,3) NOT NULL,
    total_amount                 NUMERIC(14,2) NOT NULL,
    currency                     VARCHAR(3)    NOT NULL DEFAULT 'INR',
    expected_completion          DATE,
    status                       VARCHAR(20)   NOT NULL DEFAULT 'CONFIRMED',
    created_at                   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_order_number UNIQUE (order_number),
    CONSTRAINT uq_order_quotation UNIQUE (accepted_quotation_id),
    CONSTRAINT uq_order_rfq UNIQUE (rfq_id),
    CONSTRAINT ck_order_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_order_status CHECK (status IN ('CONFIRMED','SCHEDULED','IN_PRODUCTION','QUALITY_CHECK',
        'READY_TO_SHIP','SHIPPED','DELIVERED','COMPLETED','ON_HOLD','CANCELLED'))
);

CREATE INDEX idx_rfqs_buyer        ON rfqs(buyer_organization_id);
CREATE INDEX idx_rfqs_match        ON rfqs(process_id, material_id, status);
CREATE INDEX idx_quotations_rfq    ON quotations(rfq_id);
CREATE INDEX idx_quotations_mfr    ON quotations(manufacturer_organization_id);
CREATE INDEX idx_orders_buyer      ON production_orders(buyer_organization_id);
CREATE INDEX idx_orders_mfr        ON production_orders(manufacturer_organization_id);
CREATE INDEX idx_files_org         ON file_objects(organization_id);