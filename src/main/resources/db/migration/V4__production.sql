CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE machine_reservations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id          BIGINT      NOT NULL REFERENCES machines(id),
    production_order_id BIGINT      NOT NULL REFERENCES production_orders(id),
    start_at            TIMESTAMPTZ NOT NULL,
    end_at              TIMESTAMPTZ NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    reserved_by         BIGINT      NOT NULL REFERENCES users(id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_reservation_range CHECK (end_at > start_at),
    CONSTRAINT ck_reservation_status CHECK (status IN ('ACTIVE','COMPLETED','CANCELLED')),
    -- Two ACTIVE reservations on the same machine can never overlap in time
    CONSTRAINT ex_reservation_no_overlap EXCLUDE USING gist (
        machine_id WITH =,
        tstzrange(start_at, end_at, '[)') WITH &&
    ) WHERE (status = 'ACTIVE')
);

CREATE TABLE production_order_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_order_id BIGINT      NOT NULL REFERENCES production_orders(id) ON DELETE CASCADE,
    previous_status     VARCHAR(20),
    new_status          VARCHAR(20) NOT NULL,
    updated_by          BIGINT      NOT NULL REFERENCES users(id),
    notes               TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE batches (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_order_id BIGINT        NOT NULL REFERENCES production_orders(id),
    batch_number        VARCHAR(40)   NOT NULL,
    quantity            NUMERIC(14,3) NOT NULL,
    manufacture_date    DATE,
    status              VARCHAR(25)   NOT NULL DEFAULT 'CREATED',
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_batch_number UNIQUE (batch_number),
    CONSTRAINT ck_batch_quantity CHECK (quantity > 0),
    CONSTRAINT ck_batch_status CHECK (status IN ('CREATED','IN_PROGRESS','AWAITING_INSPECTION',
        'APPROVED','REJECTED','ON_HOLD','SHIPPED','RECALLED'))
);

CREATE INDEX idx_reservations_machine ON machine_reservations(machine_id, start_at);
CREATE INDEX idx_reservations_order   ON machine_reservations(production_order_id);
CREATE INDEX idx_order_events_order   ON production_order_events(production_order_id);
CREATE INDEX idx_batches_order        ON batches(production_order_id);