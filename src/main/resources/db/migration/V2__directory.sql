CREATE TABLE manufacturing_processes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_name VARCHAR(80)  NOT NULL,
    description  VARCHAR(255),
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_process_name UNIQUE (process_name)
);

CREATE TABLE materials (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_name     VARCHAR(80)  NOT NULL,
    material_category VARCHAR(60),
    description       VARCHAR(255),
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_material_name UNIQUE (material_name)
);

CREATE TABLE manufacturer_processes (
    manufacturer_id BIGINT NOT NULL REFERENCES manufacturer_profiles(organization_id) ON DELETE CASCADE,
    process_id      BIGINT NOT NULL REFERENCES manufacturing_processes(id),
    PRIMARY KEY (manufacturer_id, process_id)
);

CREATE TABLE manufacturer_materials (
    manufacturer_id BIGINT NOT NULL REFERENCES manufacturer_profiles(organization_id) ON DELETE CASCADE,
    material_id     BIGINT NOT NULL REFERENCES materials(id),
    PRIMARY KEY (manufacturer_id, material_id)
);

CREATE TABLE machines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT        NOT NULL REFERENCES organizations(id),
    machine_name    VARCHAR(120)  NOT NULL,
    machine_type    VARCHAR(80)   NOT NULL,
    model_number    VARCHAR(80),
    serial_number   VARCHAR(80),
    capacity_value  NUMERIC(12,2),
    capacity_unit   VARCHAR(30),
    machine_status  VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    location        VARCHAR(160),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_machine_serial UNIQUE (organization_id, serial_number),
    CONSTRAINT ck_machine_status CHECK (machine_status IN ('ACTIVE','MAINTENANCE','INACTIVE')),
    CONSTRAINT ck_machine_capacity CHECK (capacity_value IS NULL OR capacity_value > 0)
);

CREATE TABLE machine_processes (
    machine_id BIGINT NOT NULL REFERENCES machines(id) ON DELETE CASCADE,
    process_id BIGINT NOT NULL REFERENCES manufacturing_processes(id),
    PRIMARY KEY (machine_id, process_id)
);

CREATE TABLE machine_materials (
    machine_id  BIGINT NOT NULL REFERENCES machines(id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES materials(id),
    PRIMARY KEY (machine_id, material_id)
);

-- Weekly working hours. day_of_week: 1 = Monday ... 7 = Sunday
CREATE TABLE machine_availability_rules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id  BIGINT  NOT NULL REFERENCES machines(id) ON DELETE CASCADE,
    day_of_week INTEGER NOT NULL,
    start_time  TIME    NOT NULL,
    end_time    TIME    NOT NULL,
    valid_from  DATE    NOT NULL DEFAULT CURRENT_DATE,
    valid_until DATE,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_rule_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_rule_time CHECK (end_time > start_time),
    CONSTRAINT ck_rule_dates CHECK (valid_until IS NULL OR valid_until >= valid_from)
);

CREATE TABLE machine_maintenance_blocks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT       NOT NULL REFERENCES machines(id) ON DELETE CASCADE,
    start_at   TIMESTAMPTZ  NOT NULL,
    end_at     TIMESTAMPTZ  NOT NULL,
    reason     VARCHAR(255),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_maintenance_range CHECK (end_at > start_at)
);

CREATE INDEX idx_machines_org        ON machines(organization_id);
CREATE INDEX idx_avail_rules_machine ON machine_availability_rules(machine_id);
CREATE INDEX idx_maintenance_machine ON machine_maintenance_blocks(machine_id, start_at);