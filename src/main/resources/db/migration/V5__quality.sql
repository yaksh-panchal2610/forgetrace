CREATE TABLE inspections (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id          BIGINT      NOT NULL REFERENCES batches(id),
    inspector_user_id BIGINT      NOT NULL REFERENCES users(id),
    inspection_type   VARCHAR(20) NOT NULL DEFAULT 'FINAL',
    status            VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    findings          TEXT,
    inspected_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_inspection_type CHECK (inspection_type IN ('INCOMING','IN_PROCESS','FINAL')),
    CONSTRAINT ck_inspection_status CHECK (status IN ('PENDING','PASSED','FAILED','ON_HOLD'))
);

CREATE TABLE inspection_measurements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id  BIGINT        NOT NULL REFERENCES inspections(id) ON DELETE CASCADE,
    parameter_name VARCHAR(100)  NOT NULL,
    expected_min   NUMERIC(14,4) NOT NULL,
    expected_max   NUMERIC(14,4) NOT NULL,
    actual_value   NUMERIC(14,4) NOT NULL,
    unit           VARCHAR(20)   NOT NULL,
    result         VARCHAR(10)   NOT NULL,
    remarks        VARCHAR(255),
    CONSTRAINT ck_measure_range CHECK (expected_max >= expected_min),
    CONSTRAINT ck_measure_result CHECK (result IN ('PASS','FAIL'))
);

-- public_token is a random UUID, never a sequential number
CREATE TABLE product_passports (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id          BIGINT       NOT NULL REFERENCES batches(id),
    public_token      UUID         NOT NULL,
    qr_file_key       VARCHAR(500),
    visibility_status VARCHAR(20)  NOT NULL DEFAULT 'PUBLIC',
    published_at      TIMESTAMPTZ,
    revoked_at        TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_passport_batch UNIQUE (batch_id),
    CONSTRAINT uq_passport_token UNIQUE (public_token),
    CONSTRAINT ck_passport_visibility CHECK (visibility_status IN ('PUBLIC','REVOKED'))
);

CREATE INDEX idx_inspections_batch     ON inspections(batch_id);
CREATE INDEX idx_inspections_inspector ON inspections(inspector_user_id);
CREATE INDEX idx_measurements_insp     ON inspection_measurements(inspection_id);